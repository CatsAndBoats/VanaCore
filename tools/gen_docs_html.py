#!/usr/bin/env python
"""gen_docs_html.py: docs\\html\\index.html, the addon docs series as one self-contained page (the markdown inlined, so it
opens from disk, double-clicked), from the page template docs\\html\\vanacore-addon-docs.html and docs\\addons\\*.md.

The template can also be served beside the markdown files, which it then fetches; here they're written into the page
as window.VANACORE_DOCS instead.

  python tools\\gen_docs_html.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
DOCS = HERE.parent / "docs" / "addons"
HTML = HERE.parent / "docs" / "html"
TEMPLATE = HTML / "vanacore-addon-docs.html"
OUT = HTML / "index.html"


def main() -> None:
    template = TEMPLATE.read_text(encoding="utf-8")
    pages = {}
    for path in sorted(DOCS.glob("*.md")) + sorted((DOCS / "examples").glob("*.md")):
        key = "docs/" + path.relative_to(DOCS).as_posix()
        pages[key] = path.read_text(encoding="utf-8")
    # the files the page lists must all be here, and every page here must be listed: a page left out of the template's
    # PAGES can't be opened (its links in the README and the other pages go nowhere)
    listed = {m.group(1) for m in re.finditer(r"file: '([^']+)'", template)}
    missing = sorted(listed - pages.keys())
    if missing:
        raise SystemExit(f"listed in the template but not in {DOCS}: {', '.join(missing)}")
    unlisted = sorted(pages.keys() - listed)
    if unlisted:
        raise SystemExit(f"not in the template's PAGES ({TEMPLATE.name}), so they can't be opened: {', '.join(unlisted)}")
    inline = "<script>window.VANACORE_DOCS = " + json.dumps(pages, ensure_ascii=False).replace("</", "<\\/") + ";</script>\n"
    title = re.search(r"<title>(.*?)</title>", template).group(1)
    body = template.replace('<script src="https://cdnjs.cloudflare.com/ajax/libs/marked', inline + '<script src="https://cdnjs.cloudflare.com/ajax/libs/marked', 1)
    page = ("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n"
            "<meta name=\"viewport\" content=\"width=device-width, initial-scale=1, viewport-fit=cover\">\n"
            f"<!-- Generated by tools/gen_docs_html.py from docs/html/vanacore-addon-docs.html and docs/addons/*.md: edit those, not this. -->\n"
            "</head>\n<body>\n" + body + "\n</body>\n</html>\n")
    OUT.write_text(page, encoding="utf-8")
    print(f"{OUT}: {len(pages)} pages, {OUT.stat().st_size / 1024:.0f} KB ({title})")


if __name__ == "__main__":
    main()
