#!/usr/bin/env python3
"""Code-quality checks over VanaCore's C/C++ (src), all run from the command line.

  cppcheck   unused variables, dead stores, leaks, bad practice, performance
  lizard     functions that are too complex (CCN), too long, or take too many parameters
  jscpd      copy-pasted code
  filelen    source files that are too long
  d3d11fx    Direct3D 11's scene effects still build from Direct3D 12's HLSL (tools/lint/d3d11_fx.py)

Run it through lint.bat, or: python tools/lint/lint.py [check ...] [--strict] [--update-baseline]

The code already has findings, so the checks are a ratchet: tools/lint/baseline.json holds what is there today, and a
run fails only for a finding that is new or has grown past its allowance (ALLOWANCE: a long file or function may
grow a little before it fails, so a two-line fix to grass.c doesn't). Fixing things never fails; `--update-baseline`
writes the improvement down so it can't be undone later. It never writes a grown finding's new value over the old one
(that would hand it a fresh allowance): `--accept-growth` does, for growth that is meant.
d3d11fx is no ratchet: Direct3D 11 without its effects is a bug, so any problem it finds fails the run.
Files whose first lines say "Generated by" or "Do not edit" (tools/gen_*.py output) are left out of every check.
Reports go to build/lint/ (not committed).
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import os
import re
import shutil
import subprocess
import sys
import time
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]  # the repository
SRC = "src"
OUT = ROOT / "build" / "lint"
BASELINE = ROOT / "tools" / "lint" / "baseline.json"

# Thresholds. Changing one changes what the baseline means: run --update-baseline after.
MAX_FILE_LINES = 1500  # filelen
LIZARD_CCN = 50  # cyclomatic complexity of one function (25 until 2026-11-06)
LIZARD_FUNC_LINES = 150  # length of one function
LIZARD_PARAMS = 8  # parameters of one function
JSCPD_MIN_TOKENS = 100  # a repeat must be at least this many tokens ...
JSCPD_MIN_LINES = 10  # ... and this many lines
JSCPD_VERSION = "4.0.5"
TIMEOUT = 25 * 60  # seconds, per tool

# How far a finding the baseline already has may grow before a run fails: (share of the baseline's value, at least,
# at most). Without it, every commit touching one of the long files or functions failed for a line or two (grass.c
# 3928 -> 3972 lines, kept_draw CCN 64 -> 65, d3d8.c 6797 -> 6802). Bigger growth still fails (build_step CCN 51 -> 57,
# stats.cpp 2231 -> 2552 lines), and so does anything the baseline hasn't (a function newly over CCN 50). cppcheck's
# counts and lizard's parameters have no allowance: a new cppcheck warning in a file is a new defect.
ALLOWANCE = {
    "filelen": (0.03, 50, 250),
    "lizard|ccn": (0.10, 3, None),
    "lizard|length": (0.10, 10, None),
    "jscpd": (0.10, 10, None),
}

SOURCE_EXTS = {".c", ".cc", ".cpp", ".h", ".hpp"}
GENERATED_EXTS = SOURCE_EXTS | {".inc"}
GENERATED_MARK = re.compile(r"generated by|do not edit", re.I)

# What cppcheck sees: the x86 Release build's defines (VanaCore.props) and include directories.
CPPCHECK_DEFINES = ["WIN32", "_WIN32", "WIN32_LEAN_AND_MEAN", "NOMINMAX", "NDEBUG", "_CRT_SECURE_NO_WARNINGS"]
CPPCHECK_INCLUDES = [
    "src/shared",
    "src/core",
    "src/gfx",
    "third_party/imgui",
    "third_party/luajit/src",
    "third_party/asmjit",
    "third_party/asmtk",
]
CPPCHECK_SUPPRESS = [
    "missingInclude",
    "missingIncludeSystem",
    "unmatchedSuppression",
    "useStlAlgorithm",  # "use std::any_of instead of this loop": taste, not a defect
    "shadowFunction",  # "argument 'silent' shadows outer function": taste too
    "*:*third_party*",
]

INSTALL = {
    "cppcheck": "winget install Cppcheck.Cppcheck   (Linux: apt install cppcheck)",
    "lizard": "python -m pip install lizard==1.24.3",
    "jscpd": "install Node.js (https://nodejs.org); npx fetches jscpd itself",
    "d3d11fx": "Windows' d3dcompiler_47.dll (in System32 from Windows 10 on): run it on Windows",
}


@dataclass
class Result:
    name: str
    status: str = "ok"  # ok | skipped | error
    findings: dict[str, int] = field(default_factory=dict)  # key -> number; a bigger number than the baseline's fails
    headline: str = ""
    report: list[str] = field(default_factory=list)
    seconds: float = 0.0
    new: dict[str, tuple[int, int, int]] = field(default_factory=dict)  # key -> (baseline, now, limit): what a run fails for
    grown: dict[str, tuple[int, int, int]] = field(default_factory=dict)  # key -> (baseline, now, limit): grown, still allowed
    fixed: int = 0
    has_baseline: bool = False


def rel(path: str) -> str:
    """A path as the baseline spells it: relative to the repository, forward slashes."""
    p = path.replace("\\", "/")
    root = ROOT.as_posix().rstrip("/") + "/"
    if p.lower().startswith(root.lower()):
        p = p[len(root):]
    return p


def is_generated(path: Path) -> bool:
    try:
        with open(path, "rb") as f:
            head = f.read(600).decode("utf-8", errors="replace")
    except OSError:
        return False
    return any(GENERATED_MARK.search(line) for line in head.splitlines()[:8])


def source_files() -> tuple[list[str], list[str]]:
    """(hand-written sources and headers, generated files), as paths relative to the repository."""
    files, generated = [], []
    for p in sorted((ROOT / SRC).rglob("*")):
        ext = p.suffix.lower()
        if ext not in GENERATED_EXTS or not p.is_file():
            continue
        if is_generated(p):
            generated.append(rel(str(p)))
        elif ext in SOURCE_EXTS:
            files.append(rel(str(p)))
    return files, generated


def run(cmd: list[str]) -> subprocess.CompletedProcess:
    # Below normal priority: a lint run shouldn't make the machine (or a game running on it) stutter.
    flags = getattr(subprocess, "BELOW_NORMAL_PRIORITY_CLASS", 0)
    return subprocess.run(
        cmd, cwd=ROOT, capture_output=True, text=True, encoding="utf-8", errors="replace",
        timeout=TIMEOUT, creationflags=flags,
    )


def skipped(name: str, why: str) -> Result:
    return Result(name, "skipped", headline=f"skipped: {why}\n   install: {INSTALL[name]}")


def failed(name: str, why: str) -> Result:
    return Result(name, "error", headline=why)


# ---- cppcheck ---------------------------------------------------------------------------------------------

def find_cppcheck() -> str | None:
    # CPPCHECK names the exe to use: GitHub's runner has its own cppcheck on PATH (2.14, a bare winlibs build without
    # its cfg folder) that would otherwise be found first.
    pinned = os.environ.get("CPPCHECK")
    if pinned and Path(pinned).exists():
        return pinned
    exe = shutil.which("cppcheck")
    if exe:
        return exe
    for var in ("ProgramFiles", "ProgramFiles(x86)"):
        base = os.environ.get(var)
        if base and (Path(base) / "Cppcheck" / "cppcheck.exe").exists():
            return str(Path(base) / "Cppcheck" / "cppcheck.exe")
    return None


CPPCHECK_LINE = re.compile(r"^(.+?)\|(\d+)\|(\w+)\|(\w+)\|(.*)$")


def parse_cppcheck(text: str) -> list[tuple[str, int, str, str, str]]:
    out = []
    for line in text.splitlines():
        m = CPPCHECK_LINE.match(line.strip())
        if m:
            out.append((rel(m.group(1)), int(m.group(2)), m.group(3), m.group(4), m.group(5)))
    return out


def check_cppcheck(args, files, generated) -> Result:
    exe = find_cppcheck()
    if not exe:
        return skipped("cppcheck", "cppcheck isn't installed")
    version = run([exe, "--version"]).stdout.strip().removeprefix("Cppcheck").strip()
    cmd = [
        exe, SRC, f"-j{args.jobs}", "--quiet",
        "--enable=warning,style,performance,portability",
        "--inline-suppr", "--std=c++20", "--platform=win32A", "--library=windows",
        "--template={file}|{line}|{severity}|{id}|{message}",
    ]
    cmd += [f"-D{d}" for d in CPPCHECK_DEFINES]
    cmd += [f"-I{d}" for d in CPPCHECK_INCLUDES if (ROOT / d).is_dir()]
    cmd += [f"--suppress={s}" for s in CPPCHECK_SUPPRESS]
    cmd += [f"--suppress=*:*{g}" for g in generated]
    proc = run(cmd)
    found = parse_cppcheck(proc.stderr + "\n" + proc.stdout)
    if proc.returncode != 0 and not found:
        # cppcheck reports a bad option or a missing library on stdout, so say both.
        said = (proc.stdout.strip() + "\n" + proc.stderr.strip()).strip()[-600:]
        return failed("cppcheck", f"cppcheck {version} exited {proc.returncode}: {said}")

    res = Result("cppcheck")
    by_id: dict[str, int] = {}
    for f, line, sev, ident, msg in found:
        key = f"{f}|{ident}"
        res.findings[key] = res.findings.get(key, 0) + 1
        by_id[ident] = by_id.get(ident, 0) + 1
        res.report.append(f"{f}:{line}: {sev}: {msg} [{ident}]")
    top = ", ".join(f"{i} {n}" for i, n in sorted(by_id.items(), key=lambda kv: -kv[1])[:6])
    res.headline = f"cppcheck {version}: {len(found)} findings in {len({f for f, *_ in found})} files" + (f"\n   most: {top}" if top else "")
    return res


# ---- lizard -----------------------------------------------------------------------------------------------

LIZARD_LINE = re.compile(r"^(.+?):(\d+): warning: (.+?) has (\d+) NLOC, (\d+) CCN, (\d+) token, (\d+) PARAM, (\d+) length")


def parse_lizard(text: str) -> list[tuple[str, int, str, int, int, int, int]]:
    """(file, line, function, nloc, ccn, params, length)."""
    out = []
    for line in text.splitlines():
        m = LIZARD_LINE.match(line.strip())
        if m:
            out.append((rel(m.group(1)), int(m.group(2)), m.group(3), int(m.group(4)), int(m.group(5)), int(m.group(7)), int(m.group(8))))
    return out


def check_lizard(args, files, generated) -> Result:
    if importlib.util.find_spec("lizard") is None:
        return skipped("lizard", "the lizard Python package isn't installed")
    cmd = [
        sys.executable, "-m", "lizard", SRC, "-l", "cpp", "-w", f"-t{args.jobs}",
        "-C", str(LIZARD_CCN), "-L", str(LIZARD_FUNC_LINES), "-a", str(LIZARD_PARAMS),
    ]
    for g in generated:
        cmd += ["-x", f"*/{g}"]
    proc = run(cmd)
    found = parse_lizard(proc.stdout)
    if proc.returncode not in (0, 1) or (proc.returncode == 1 and not found and proc.stderr.strip()):
        return failed("lizard", f"lizard exited {proc.returncode}: {proc.stderr.strip()[-400:]}")

    res = Result("lizard")
    for f, line, fn, nloc, ccn, params, length in found:
        for metric, value, limit in (("ccn", ccn, LIZARD_CCN), ("length", length, LIZARD_FUNC_LINES), ("params", params, LIZARD_PARAMS)):
            if value > limit:
                key = f"{f}|{fn}|{metric}"
                res.findings[key] = max(res.findings.get(key, 0), value)
        res.report.append(f"{f}:{line}: {fn}: CCN {ccn}, {length} lines, {params} parameters")
    worst = sorted(found, key=lambda t: -t[4])[:3]
    res.headline = (
        f"lizard: {len(found)} functions over CCN {LIZARD_CCN}, {LIZARD_FUNC_LINES} lines or {LIZARD_PARAMS} parameters"
        + ("\n   most complex: " + ", ".join(f"{fn} (CCN {ccn})" for _, _, fn, _, ccn, _, _ in worst) if worst else "")
    )
    return res


# ---- jscpd ------------------------------------------------------------------------------------------------

def check_jscpd(args, files, generated) -> Result:
    npx = shutil.which("npx")
    if not npx:
        return skipped("jscpd", "Node.js (npx) isn't installed")
    out = OUT / "jscpd"
    shutil.rmtree(out, ignore_errors=True)
    cmd = [
        npx, "--yes", f"jscpd@{JSCPD_VERSION}", SRC, "--format", "c,cpp",
        "--min-tokens", str(JSCPD_MIN_TOKENS), "--min-lines", str(JSCPD_MIN_LINES), "--max-size", "5mb",
        "--reporters", "json", "--output", str(out), "--silent",
    ]
    if generated:
        cmd += ["--ignore", ",".join(f"**/{g}" for g in generated)]
    proc = run(cmd)
    report = out / "jscpd-report.json"
    if not report.exists():
        return failed("jscpd", f"jscpd made no report (exit {proc.returncode}): {(proc.stderr or proc.stdout).strip()[-400:]}")

    data = json.loads(report.read_text(encoding="utf-8"))
    res = Result("jscpd")
    for d in data.get("duplicates", []):
        a, b = rel(d["firstFile"]["name"]), rel(d["secondFile"]["name"])
        key = "|".join(sorted((a, b)))
        res.findings[key] = res.findings.get(key, 0) + int(d.get("lines", 0))
        res.report.append(
            f"{a}:{d['firstFile'].get('start')}-{d['firstFile'].get('end')}  =  "
            f"{b}:{d['secondFile'].get('start')}-{d['secondFile'].get('end')}  ({d.get('lines')} lines, {d.get('tokens')} tokens)"
        )
    total = data.get("statistics", {}).get("total", {})
    res.headline = (
        f"jscpd {JSCPD_VERSION}: {len(data.get('duplicates', []))} repeated blocks, "
        f"{total.get('duplicatedLines', '?')} lines ({total.get('percentage', '?')}% of the code)"
    )
    return res


# ---- file length ------------------------------------------------------------------------------------------

def check_filelen(args, files, generated) -> Result:
    res = Result("filelen")
    for f in files:
        data = (ROOT / f).read_bytes()
        lines = data.count(b"\n") + (1 if data and not data.endswith(b"\n") else 0)
        if lines > MAX_FILE_LINES:
            res.findings[f] = lines
    longest = sorted(res.findings.items(), key=lambda kv: -kv[1])
    res.report = [f"{f}: {n} lines" for f, n in longest]
    res.headline = f"filelen: {len(longest)} of {len(files)} files over {MAX_FILE_LINES} lines" + (
        "\n   longest: " + ", ".join(f"{f.rsplit('/', 1)[-1]} ({n})" for f, n in longest[:3]) if longest else ""
    )
    return res


# ---- Direct3D 11's scene effects --------------------------------------------------------------------------

def check_d3d11fx(args, files, generated) -> Result:
    # A problem is an error, not a finding held to the baseline: what it finds turns Direct3D 11's effects off
    try:
        import ctypes
        ctypes.WinDLL("d3dcompiler_47.dll")
    except (AttributeError, OSError):
        return skipped("d3d11fx", "d3dcompiler_47.dll can't be loaded")
    spec = importlib.util.spec_from_file_location("d3d11_fx", Path(__file__).with_name("d3d11_fx.py"))
    d3d11_fx = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(d3d11_fx)
    summary, problems = d3d11_fx.check()
    if problems:
        res = failed("d3d11fx", f"d3d11fx: {summary}\n   " + "\n   ".join(problems[:10]))
        res.report = problems
        return res
    return Result("d3d11fx", headline=f"d3d11fx: {summary}")


CHECKS = {"cppcheck": check_cppcheck, "lizard": check_lizard, "jscpd": check_jscpd, "filelen": check_filelen, "d3d11fx": check_d3d11fx}


# ---- baseline ---------------------------------------------------------------------------------------------

def load_baseline() -> dict:
    try:
        return json.loads(BASELINE.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}


def allowance(check: str, key: str, was: int) -> int:
    """How much a finding at `was` in the baseline may grow before it fails (0 for one the baseline hasn't)."""
    if was <= 0:
        return 0
    rule = ALLOWANCE.get(f"{check}|{key.rsplit('|', 1)[-1]}" if check == "lizard" else check)
    if not rule:
        return 0
    share, least, most = rule
    n = max(least, int(was * share))
    return min(n, most) if most else n


def compare(res: Result, baseline: dict) -> None:
    base = baseline.get(res.name)
    res.has_baseline = isinstance(base, dict)
    if not res.has_baseline:
        return
    for key, now in res.findings.items():
        was = base.get(key, 0)
        if now <= was:
            continue
        limit = was + allowance(res.name, key, was)
        (res.new if now > limit else res.grown)[key] = (was, now, limit)
    res.fixed = sum(1 for key, was in base.items() if res.findings.get(key, 0) < was)


def save_baseline(baseline: dict, results: list[Result], accept_growth: bool) -> int:
    """Writes today's findings, except that one the baseline has keeps its old value where it has grown (unless
    accept_growth). Returns how many were kept so."""
    kept = 0
    for res in results:
        if res.status != "ok":
            continue
        old = baseline.get(res.name)
        found = dict(res.findings)
        if isinstance(old, dict) and not accept_growth:
            for key, now in found.items():
                if 0 < old.get(key, 0) < now:
                    found[key] = old[key]
                    kept += 1
        baseline[res.name] = dict(sorted(found.items()))
    baseline["_note"] = "Written by tools/lint/lint.py --update-baseline. A run fails only for a finding not here or bigger than here."
    with open(BASELINE, "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(baseline, indent=1, sort_keys=True) + "\n")
    return kept


# ---- main -------------------------------------------------------------------------------------------------

def main() -> int:
    for stream in (sys.stdout, sys.stderr):
        stream.reconfigure(errors="replace")
    ap = argparse.ArgumentParser(description="Code-quality checks over VanaCore's C/C++ (see the top of this file).")
    ap.add_argument("checks", nargs="*", metavar="check", help="which to run: " + ", ".join(CHECKS) + " (default: all)")
    ap.add_argument("--strict", action="store_true", help="a check whose tool isn't installed fails the run (CI)")
    ap.add_argument("--update-baseline", action="store_true", help="write today's findings to baseline.json (a grown one keeps its old value)")
    ap.add_argument("--accept-growth", action="store_true", help="with --update-baseline: write grown findings' new values too")
    ap.add_argument("--report-only", action="store_true", help="print the findings, never fail on them")
    ap.add_argument("--jobs", type=int, default=min(4, os.cpu_count() or 1), help="threads for the tools that take them (default 4)")
    args = ap.parse_args()
    unknown = [c for c in args.checks if c not in CHECKS]
    if unknown:
        ap.error(f"unknown check {unknown[0]!r}: pick from {', '.join(CHECKS)}")
    names = args.checks or list(CHECKS)

    files, generated = source_files()
    OUT.mkdir(parents=True, exist_ok=True)
    baseline = load_baseline()
    print(f"lint: {len(files)} source files in {SRC}/ ({len(generated)} generated, left out)")

    results = []
    for name in names:
        started = time.time()
        try:
            res = CHECKS[name](args, files, generated)
        except subprocess.TimeoutExpired:
            res = failed(name, f"timed out after {TIMEOUT // 60} minutes")
        res.seconds = time.time() - started
        compare(res, baseline)
        if res.report:
            (OUT / f"{name}.txt").write_text("\n".join(res.report) + "\n", encoding="utf-8")
        results.append(res)

        print(f"\n== {name} ({res.seconds:.0f}s) ==\n   {res.headline}")
        if res.status != "ok":
            continue
        if not res.has_baseline:
            print("   no baseline yet: nothing to compare with (lint.bat --update-baseline writes one)")
        else:
            if res.new:
                print(f"   WORSE than the baseline: {len(res.new)}")
                for key, (was, now, limit) in sorted(res.new.items())[:40]:
                    allowed = f" (allowed up to {limit})" if limit > was else ""
                    print(f"     {key.replace('|', '  ')}   {was} -> {now}{allowed}")
                if len(res.new) > 40:
                    print(f"     ... {len(res.new) - 40} more (build/lint/{name}.txt has them all)")
            else:
                print("   no worse than the baseline" + (f"; {res.fixed} better (--update-baseline keeps it)" if res.fixed else ""))
            if res.grown:
                print(f"   grown, within the allowance (passes): {len(res.grown)}")
                for key, (was, now, limit) in sorted(res.grown.items()):
                    print(f"     {key.replace('|', '  ')}   {was} -> {now} (fails over {limit})")
                    if os.environ.get("GITHUB_ACTIONS"):
                        print(f"::warning title=lint {name}: grown within the allowance::{key.replace('|', '  ')}  {was} -> {now} (fails over {limit})")

    if args.update_baseline:
        kept = save_baseline(baseline, results, args.accept_growth)
        print(f"\nbaseline written: {BASELINE.relative_to(ROOT).as_posix()} (commit it)")
        if kept:
            print(f"   {kept} grown findings kept at the baseline's value (--accept-growth writes today's)")

    summary = ["| check | result | offenders | vs baseline |", "|---|---|---|---|"]
    for r in results:
        vs = "-" if r.status != "ok" or not r.has_baseline else (f"{len(r.new)} worse" if r.new else "ok")
        if r.status == "ok" and r.grown:
            vs += f", {len(r.grown)} grown within the allowance"
        summary.append(f"| {r.name} | {r.status} | {len(r.findings) if r.status == 'ok' else '-'} | {vs} |")
    (OUT / "summary.md").write_text("\n".join(summary) + "\n", encoding="utf-8")
    if os.environ.get("GITHUB_STEP_SUMMARY"):
        with open(os.environ["GITHUB_STEP_SUMMARY"], "a", encoding="utf-8") as f:
            f.write("## Lint\n\n" + "\n".join(summary) + "\n")

    print("\n" + "\n".join(summary))
    bad = [r for r in results if r.status == "error" or (args.strict and r.status == "skipped")]
    worse = [r for r in results if r.new]
    if args.report_only or args.update_baseline:
        return 1 if bad else 0
    return 1 if bad or worse else 0


if __name__ == "__main__":
    sys.exit(main())
